// Compiles content/stories/*.json into src/js/stories.js (the text of every book).
// Usage: node tools/build-stories.js
const fs = require('fs'); const path = require('path');
const root = path.resolve(__dirname, '..'), dir = path.join(root, 'content', 'stories');
const files = fs.readdirSync(dir).filter((f) => /^\d\d-.*\.json$/.test(f)).sort();
const out = []; let volumes = 0, words = 0;
for (const f of files) {
  const sec = Number(f.slice(0, 2)), d = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  d.series.forEach((s, i) => {
    out[sec * 4 + i] = s.volumes.map((v) => { volumes++; words += v.text.split(/\s+/).length; return [v.title.trim(), v.text.replace(/\r/g, '').replace(/[ \t]+\n/g, '\n').trim()]; });
  });
}
for (let i = 0; i < 96; i++) if (!out[i]) out[i] = null;
const js = '// The Night Shelver — the text of every book. Generated by tools/build-stories.js from content/stories/*.json; edit those, not this.\n'
  + 'window.TH.STORIES = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(root, 'src', 'js', 'stories.js'), js);
console.log(`${files.length} section file(s), ${volumes} books, ${words} words -> src/js/stories.js (${(js.length / 1024).toFixed(0)} KB)`);
